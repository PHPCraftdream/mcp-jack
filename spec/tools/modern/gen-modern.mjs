// Deterministic generator for spec/fixtures/modern and spec/tests/modern/CASES.md.
//   node gen-modern.mjs          write files
//   node gen-modern.mjs --check  verify files on disk are up to date
// Each family (headers, streams, webhooks) exports { family, build() } from its index.mjs.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import headers from './headers/index.mjs';
import streams from './streams/index.mjs';
import webhooks from './webhooks/index.mjs';

const SPEC = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const FAMILIES = [headers, streams, webhooks];
const json = (v) => `${JSON.stringify(v, null, 2)}\n`;

function collect() {
  const out = new Map();
  const markdown = [
    '# Modern profile conformance cases',
    '',
    'Generated by `tools/modern/gen-modern.mjs`. Do not edit by hand.',
    '',
  ];
  for (const fam of FAMILIES) {
    const built = fam.build();
    for (const [name, value] of Object.entries(built.files).sort(([a], [b]) => (a < b ? -1 : 1))) {
      const rel = `fixtures/modern/${name}`;
      if (out.has(rel)) throw new Error(`duplicate fixture file: ${rel}`);
      out.set(rel, json(value));
    }
    markdown.push(`## ${fam.family}`, '', built.casesMarkdown.trimEnd(), '');
  }
  out.set('tests/modern/CASES.md', `${markdown.join('\n')}`);
  return out;
}

const OUT = collect();
if (process.argv.includes('--check')) {
  const stale = [...OUT].filter(([p, c]) => !existsSync(join(SPEC, p)) || readFileSync(join(SPEC, p), 'utf8') !== c);
  if (stale.length) {
    console.error(`stale: ${stale.map(([p]) => p).join(', ')}`);
    process.exit(1);
  }
  console.log(`ok: ${OUT.size} modern files up to date`);
} else {
  for (const [p, c] of OUT) {
    mkdirSync(dirname(join(SPEC, p)), { recursive: true });
    writeFileSync(join(SPEC, p), c);
  }
  console.log(`wrote ${OUT.size} modern files: ${[...OUT.keys()].join(', ')}`);
}
