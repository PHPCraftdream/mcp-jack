// Webhooks family of the M0 modern-profile vectors: build() and the generated case index.
import { NOW, deepEqual, stableStringify } from '../../gen/core.mjs';
import { RULES, RULE_IDS, RULE_VECTORS } from './rules.mjs';
import * as signatures from './vectors/signatures.mjs';
import * as w1 from './vectors/w1.mjs';
import * as receiver from './vectors/receiver.mjs';
import * as endpoint from './vectors/endpoint.mjs';
import * as ssrf from './vectors/ssrf.mjs';
import * as subscription from './vectors/subscription.mjs';
import * as card from './vectors/card.mjs';

export const family = 'webhooks';
const FAMILIES = [signatures, w1, receiver, endpoint, ssrf, subscription, card];
const REQUIRED = ['id', 'rule', 'kind', 'input', 'expect'];
// A description is required: the spec's vector-file schema promises one on every case.
// It must be a non-empty string, checked with the required members.
function checkDescription(c) {
  if (c.description === undefined) throw new Error(`case ${c.id} is missing its description`);
  if (typeof c.description !== 'string' || c.description.length === 0) {
    throw new Error(`case ${c.id} has a non-string description`);
  }
}
const NOTE = 'TEST ONLY. Generated by spec/tools/modern/webhooks/index.mjs; see spec/06-webhooks.md.';
const CLOCK = [
  `Fixed clock: now = ${NOW} (2026-01-01T00:00:00Z).`,
  'Fixture identities: `newbie` (current webhook signing key), `newbie2` (rotation predecessor),',
  '`newbie3` (successor), `mallory` (never published), `svc` (MCP server response key, never a webhook key).',
  'Fixture keys are test-only.',
].join(' ');

// RULE_VECTORS is declared independently of the cases, so check it names exactly the collected set.
function assertRuleVectors(entries) {
  const byId = new Map(entries.map((entry) => [entry.case.id, entry.case]));
  const declared = new Set();
  for (const rule of RULES) {
    const ids = Object.hasOwn(RULE_VECTORS, rule.id) ? RULE_VECTORS[rule.id] : undefined;
    if (!Array.isArray(ids) || ids.length === 0) throw new Error(`rule ${rule.id} declares no case ids`);
    for (const id of ids) {
      if (!byId.has(id)) throw new Error(`rule ${rule.id} declares unknown case ${id}`);
      const c = byId.get(id);
      if (c.rule !== rule.id) throw new Error(`case ${id} is declared under ${rule.id} but carries ${c.rule}`);
      if (declared.has(id)) throw new Error(`case ${id} is declared twice`);
      declared.add(id);
    }
  }
  for (const { case: c } of entries) {
    if (!declared.has(c.id)) throw new Error(`case ${c.id} is missing from RULE_VECTORS[${c.rule}]`);
  }
}

// Every case of every family, in family order then module order, each with the module that runs it.
function collect() {
  const entries = [];
  const seen = new Set();
  for (const mod of FAMILIES) {
    for (const c of mod.cases) {
      if (seen.has(c.id)) throw new Error(`duplicate case id: ${c.id}`);
      for (const member of REQUIRED) {
        if (c[member] === undefined) throw new Error(`case ${c.id} is missing ${member}`);
      }
      checkDescription(c);
      if (!RULE_IDS.has(c.rule)) throw new Error(`rule ${c.rule} of case ${c.id} is not declared in rules.mjs`);
      seen.add(c.id);
      entries.push({ mod, case: c });
    }
  }
  for (const rule of RULES) {
    if (!entries.some((entry) => entry.case.rule === rule.id)) throw new Error(`rule ${rule.id} has no case`);
  }
  assertRuleVectors(entries);
  return entries;
}

// The reference must reproduce the expectation written in the vector, field for field.
function agree(c, mod) {
  const got = mod.run(c);
  if (!deepEqual(got, c.expect)) {
    throw new Error(
      `case ${c.id} (rule ${c.rule}): reference disagrees:\n` +
        `  got:  ${stableStringify(got)}\n  want: ${stableStringify(c.expect)}`,
    );
  }
}

const idsOf = (cases) => cases.map((c) => `\`${c.id}\``).join(', ');
const kindsOf = (mod) => {
  const kinds = [];
  for (const c of mod.cases) if (!kinds.includes(c.kind)) kinds.push(c.kind);
  return kinds;
};

// The index document, derived only from the modules and the rule list.
function markdown(families) {
  const cases = families.flatMap((mod) => mod.cases);
  const rules = new Set(cases.map((c) => c.rule));
  const lines = [
    '# Webhook conformance cases',
    'Generated by `spec/tools/modern/webhooks/index.mjs`. Do not edit by hand.',
    '',
    CLOCK,
    '',
    '## Files',
    '',
    '| file | cases |',
    '| --- | --- |',
    ...families.map((mod) => `| \`${mod.file}\` | ${mod.cases.length} |`),
    `| **total** | **${cases.length}** |`,
    '',
    '## Cases per rule',
    '',
    '| rule | title | case ids |',
    '| --- | --- | --- |',
    ...RULES.map((rule) => `| ${rule.id} | ${rule.title} | ${idsOf(cases.filter((c) => c.rule === rule.id))} |`),
    '',
    '## Case shapes',
    '',
    ...families.map((mod) => `- \`${mod.file}\`: kinds ${kindsOf(mod).join(', ')}`),
    '',
    `Total: ${cases.length} cases, ${rules.size} rules covered.`,
  ];
  return `${lines.join('\n')}\n`;
}

// Pure: reads the modules and the clock constant, never sorts or mutates a case.
export function build() {
  for (const entry of collect()) agree(entry.case, entry.mod);
  return {
    files: Object.fromEntries(FAMILIES.map((mod) => [mod.file, { note: NOTE, clock: NOW, cases: mod.cases }])),
    casesMarkdown: markdown(FAMILIES),
  };
}

// The family entry point the parent integration calls.
export default { family, build };
