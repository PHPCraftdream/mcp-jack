// Case index markdown of spec 04 section 8. Pure: no I/O, no clock, no
// randomness, no mutation of the cases it reads.
import { ALL_RULES, REASONS } from '../spec-data.mjs';

const LF = '\n';

// Cell hygiene: escape pipes, keep every cell on one line.
const cell = (value) => String(value).replace(/\|/g, '\\|').replace(/\r\n|[\r\n]/g, ' ');

const idCell = (id) => '`' + cell(id) + '`';

const row = (cells) => '| ' + cells.map(cell).join(' | ') + ' |';

const table = (columns, rows) => [
  '| ' + columns.join(' | ') + ' |',
  '|' + columns.map(() => '---').join('|') + '|',
  ...rows,
];

const section = (title, columns, rows) => [title, '', ...table(columns, rows)].join(LF);

// A resolved refusal carries the wire outcome, so the reason token of the 5.1
// table is recovered by its fixed message.
const reasonToken = (expect) => Object.keys(REASONS).find((token) => REASONS[token].message === expect.error.message);

// `<http_status>` `<jsonrpc_code>` `<reason>`, from the reason table of 5.1.
const requestExpected = (c) => {
  if (c.expect.outcome === 'forward') return 'forward (' + c.expect.era + ')';
  // The classification refusal of 02 section 2 item 4 has a string error code and
  // no reason token in the 5.1 table, so it names the classification instead.
  if (c.expect.outcome === 'refuse_invalid_request') {
    return c.expect.http_status + ' `' + c.expect.error.code + '` (classification, era-neutral)';
  }
  return c.expect.http_status + ' `' + c.expect.error.code + '` `' + reasonToken(c.expect) + '`';
};

const encodingExpected = (c) => {
  if (c.kind === 'build') return '_meta + ' + c.expect.headers.length + ' header(s)';
  if (c.kind === 'encode') return c.expect.header_value === '' ? '(empty)' : '`' + c.expect.header_value + '`';
  return c.expect.ok ? 'ok' : c.expect.reason;
};

const annotationExpected = (c) => {
  if (c.kind.startsWith('validate')) return c.expect.valid ? 'valid' : 'invalid (' + c.expect.reason + ')';
  if (c.expect.outcome === 'headers') return c.expect.headers.length + ' header(s)';
  return 'refuse (' + c.expect.reason + ')';
};

const eraExpected = (expect) => {
  let text = expect.era + ' / ' + expect.action;
  if (expect.reason !== null) text += ' / ' + expect.reason;
  if (Object.hasOwn(expect, 'supported')) text += ' / supported=' + JSON.stringify(expect.supported);
  return text;
};

const statusOf = (c) => (c.response ? c.response.status : c.status);
const verifiedOf = (c) => (c.response ? c.response.verified : c.verified);

const vectorsCell = (vectors) => vectors.map(idCell).join(', ');

export function buildCasesMarkdown({ requestCases, byReference = [], encodingCases, annotationCases, eraCases, now, aud }) {
  const requestRows = requestCases.map((c) => row([
    idCell(c.id), c.rule, c.profile, c.description, requestExpected(c),
  ]));
  const encodingRows = encodingCases.map((c) => row([
    idCell(c.id), c.rule, c.kind, c.description, encodingExpected(c),
  ]));
  const annotationRows = annotationCases.map((c) => row([
    idCell(c.id), c.rule, c.kind, c.description, annotationExpected(c),
  ]));
  const eraRows = eraCases.map((c) => row([
    idCell(c.id), c.rule, statusOf(c), verifiedOf(c), c.description, eraExpected(c.expect),
  ]));
  const byReferenceRows = byReference.map((e) => row([
    idCell(e.id), e.rule, idCell(e.file), vectorsCell(e.vectors),
  ]));

  const all = [...requestCases, ...encodingCases, ...annotationCases, ...eraCases];
  const coverageRows = ALL_RULES
    .map((rule) => [rule, all.filter((c) => c.rule === rule).length])
    .filter(([, count]) => count > 0)
    .map(([rule, count]) => row([rule, count]));

  const parts = [
    '# Modern profile header cases',
    'Generated by `tools/modern/headers/index.mjs` (`build().casesMarkdown`). Do not edit by hand.',
    'Fixed clock: now = ' + cell(now) + ', aud = `' + cell(aud) + '`. These are classification-level cases: request authentication (`mcp-jack/v1`) and the legacy dispatch rules of spec 02 run before every case and are covered by `request-vectors.json` and `admin-vectors.json`, not here.',
    section(
      '## Request classification (`fixtures/modern/modern-request-vectors.json`, ' + requestCases.length + ' cases)',
      ['id', 'rule', 'profile', 'description', 'expected'],
      requestRows,
    ),
    section(
      '## Value encoding and request construction (`fixtures/modern/header-encoding-vectors.json`, ' + encodingCases.length + ' cases)',
      ['id', 'rule', 'kind', 'description', 'expected'],
      encodingRows,
    ),
    section(
      '## x-mcp-header validation and projection (`fixtures/modern/x-mcp-header-vectors.json`, ' + annotationCases.length + ' cases)',
      ['id', 'rule', 'kind', 'description', 'expected'],
      annotationRows,
    ),
    section(
      '## Era detection (`fixtures/modern/era-detection-vectors.json`, ' + eraCases.length + ' cases)',
      ['id', 'rule', 'status', 'verified', 'description', 'expected'],
      eraRows,
    ),
    ...(byReference.length > 0 ? [section(
      '## By-reference cases (`fixtures/modern/modern-request-vectors.json`, ' + byReference.length + ' entries)',
      ['id', 'rule', 'file', 'vectors'],
      byReferenceRows,
    )] : []),
    section('## Rule coverage', ['rule', 'cases'], coverageRows),
    'Rules `C7`, `C8`, `C10` and `C12` have no cases here: they are verified by SDK unit tests (spec 04 section 8).',
  ];

  return parts.join(LF + LF) + LF;
}
