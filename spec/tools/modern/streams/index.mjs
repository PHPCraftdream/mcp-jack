// spec/tools/modern/streams/index.mjs
// Generates the two s1 stream fixtures and the case table (spec 05 section 9).
// Every client expectation and every build case is checked against the
// independent reference implementation before anything is emitted.
import { Buffer } from 'node:buffer';
import { NOW, WINDOW, deepEqual, stableStringify } from '../../gen/core.mjs';
import { CLIENT_CODES, buildStream, parseSignal, verifyStream } from './reference.mjs';
import { MARKER, SID, SID2, SVC, authHeaders, bytes, chunk } from './fixtures.mjs';
import { CASES, CLIENT_COUNT, EXEMPT, REQUIREMENTS, RULES, checkRequirements } from './rules.mjs';
import { buildVectors, buildCaseChecks } from './vectors/vectors-build.mjs';

const NOTE = 'TEST ONLY. Generated by spec/tools/modern/streams/index.mjs; do not edit by hand.';
const ID_RE = /^stream-[a-z0-9-]+$/;

const disagree = (id, got, want) => new Error(
  `${id}: reference disagrees: got ${stableStringify(got)} want ${stableStringify(want)}`,
);

// Section 9 data_fill: a marker chunk expands to N copies of one ASCII byte
// before the body is parsed.
const expand = (c) => ({
  status: c.response.status,
  headers: c.response.headers,
  stream_b64u: c.response.stream_b64u.map((piece) => (piece === MARKER
    ? chunk(bytes(c.data_fill.byte.repeat(c.data_fill.count)))
    : piece)),
});

// 9 expect.messages: either the delivered string or a marker that expands to N
// copies of one ASCII byte.
const expandMessage = (m) => (typeof m === 'string' ? m : m.data_fill.byte.repeat(m.data_fill.count));

// 6.3: the final JSON-RPC response of the opening request is a 2.0 object with
// no method, exactly one of result or error, and that request's own id.
function isRpcResponse(text, requestId) {
  let value;
  try {
    value = JSON.parse(text);
  } catch {
    return false;
  }
  if (typeof value !== 'object' || value === null || Array.isArray(value)) return false;
  if (value.jsonrpc !== '2.0' || Object.hasOwn(value, 'method')) return false;
  if (JSON.stringify(value.id) !== JSON.stringify(requestId)) return false;
  return Object.hasOwn(value, 'result') !== Object.hasOwn(value, 'error');
}

const streamCompare = (c, got) => {
  const { mcp_complete: mc, ...rest } = c.expect;
  const want = { ...rest, messages: rest.messages.map(expandMessage) };
  if (!deepEqual(got, want)) throw disagree(c.id, got, want);
  if (mc !== undefined) {
    const last = got.messages[got.messages.length - 1];
    const complete = last !== undefined && isRpcResponse(last, c.state.request_id);
    if (complete !== mc) throw disagree(`${c.id} mcp_complete`, complete, mc);
  }
};

// Rebuild one case's expectation from its input with the reference signer.
const signedExpect = (input) => {
  const out = buildStream({
    privKey: SVC.priv,
    kid: input.kid,
    sid: input.sid,
    status: input.status,
    requestSig: input.request_sig,
    openTs: input.open_ts,
    frames: input.frames,
  });
  return {
    jack_auth: out.jack_auth,
    open_signing_string: out.open_signing_string,
    frames: out.frames,
    stream_b64u: chunk(bytes(out.body)),
  };
};

function checkCases(cases) {
  const ids = new Set();
  for (const c of cases) {
    if (!ID_RE.test(c.id)) throw new Error(`${c.id}: id does not match ${ID_RE}`);
    if (ids.has(c.id)) throw new Error(`${c.id}: duplicate id`);
    ids.add(c.id);
    const got = verifyStream({
      response: expand(c),
      state: c.state,
      silentAfterMs: c.silent_after_ms,
      arrivalMs: c.arrival_ms,
      consumer: c.consumer,
    });
    streamCompare(c, got);
  }
  return ids;
}

function checkBuilds() {
  const checks = new Map(buildCaseChecks.map((c) => [c.id, c]));
  const ids = new Set();
  for (const c of buildVectors) {
    ids.add(c.id);
    if (!deepEqual(c.expect, signedExpect(c.input))) throw disagree(c.id, c.expect, signedExpect(c.input));
    const check = checks.get(c.id);
    if (check === undefined) throw new Error(`${c.id}: no buildCaseChecks entry`);
    const got = verifyStream({
      response: {
        status: 200,
        headers: authHeaders(c.expect.jack_auth),
        stream_b64u: [c.expect.stream_b64u],
      },
      state: check.state,
    });
    // 4.3 step 6: a 2.18 signal frame is verified but never delivered.
    const want = {
      messages: check.expectedMessages.filter((data) => parseSignal(data) === null),
      terminal: check.expectedTerminal,
    };
    if (!deepEqual(got, want)) throw disagree(c.id, got, want);
  }
  return ids;
}

const expectCell = (c) => (c.expect.terminal.state === 'ok'
  ? `ok (${c.expect.messages.length} messages)`
  : `\`${c.expect.terminal.code}\` after ${c.expect.terminal.frames_verified} frames, ${c.expect.messages.length} messages`);

const buildCell = (c) => {
  const size = Buffer.from(c.expect.stream_b64u, 'base64url').length;
  return `ok, ${c.expect.frames.length} frames, ${size} body bytes`;
};

function casesMarkdown(cases) {
  const errors = cases.filter((c) => c.expect.terminal.state === 'error');
  const codes = new Set(errors.map((c) => c.expect.terminal.code));
  const clientRows = cases.map((c) => `| \`${c.id}\` | ${c.description} | ${expectCell(c)} |`);
  const buildRows = buildVectors.map((c) => `| \`${c.id}\` | ${c.description} | ${buildCell(c)} |`);
  const ruleRows = RULES.map((rule) => {
    if (EXEMPT.includes(rule)) return `| \`${rule}\` | - | - exempt (see spec Exemptions) |`;
    const { requirement, vectors } = REQUIREMENTS[rule];
    return `| \`${rule}\` | ${requirement} | ${vectors.map((id) => `\`${id}\``).join(', ')} |`;
  });
  const mapped = Object.keys(REQUIREMENTS).length;
  return [
    '# Signed stream cases (`s1`)',
    '',
    'Generated by `spec/tools/modern/streams/index.mjs`. Do not edit by hand.',
    '',
    `Fixed clock: now = ${NOW}, window = ${WINDOW} s, stream key \`svc\` (\`kid\` ${SVC.kid}),`
      + ` fixed sids ${SID} and ${SID2}.`,
    '',
    `## Client verification (\`fixtures/modern/stream-vectors.json\`, ${cases.length} cases)`,
    '',
    '| id | description | expected |',
    '|---|---|---|',
    ...clientRows,
    '',
    `## Server signing (\`fixtures/modern/stream-build-vectors.json\`, ${buildVectors.length} cases)`,
    '',
    '| id | description | expected |',
    '|---|---|---|',
    ...buildRows,
    '',
    '## Rule coverage',
    '',
    '| rule | requirement | vectors |',
    '|---|---|---|',
    ...ruleRows,
    '',
    '## Counts',
    '',
    `- client cases: ${cases.length} (${errors.length} errors, ${cases.length - errors.length} positives)`,
    `- build cases: ${buildVectors.length}`,
    `- error codes covered ${codes.size} of ${CLIENT_CODES.length}`,
    `- rules mapped ${mapped}`,
    `- rules exempt ${EXEMPT.length}`,
    '',
  ].join('\n');
}

export default {
  family: 'streams',
  build() {
    if (CASES.length !== CLIENT_COUNT) {
      throw new Error(`expected ${CLIENT_COUNT} client cases, got ${CASES.length}`);
    }
    const clientIds = checkCases(CASES);
    const buildIds = checkBuilds();
    checkRequirements(clientIds, buildIds);
    return {
      files: {
        'stream-vectors.json': { note: NOTE, cases: CASES },
        'stream-build-vectors.json': { note: NOTE, cases: buildVectors },
      },
      casesMarkdown: casesMarkdown(CASES),
    };
  },
};
