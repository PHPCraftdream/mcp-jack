// Deterministic generator for interop/sign-cases.json.
//   node gen-sign-cases.mjs          write file
//   node gen-sign-cases.mjs --check  verify file on disk is up to date
// Oracle values pin the exact bytes of spec/01-authentication.md section 3.1
// and are cross-checked against spec/tools/reference-verifier.mjs.
import { createPrivateKey, sign } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { b64u, sha256, kidOf, requestSigningString } from '../../spec/tools/reference-verifier.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT_REL = 'interop/sign-cases.json';
const AUD = 'https://svc.example.test';
const PKCS8_PREFIX = Buffer.from('302e020100300506032b657004220420', 'hex');

// Keys are TEST ONLY: read seeds/kids from spec/fixtures/keys.json, never hardcode them.
const keyEntries = JSON.parse(readFileSync(join(ROOT, 'spec/fixtures/keys.json'), 'utf8')).keys;
const K = Object.fromEntries(keyEntries.map((e) => {
  const seed = Buffer.from(e.seed_hex, 'hex');
  const priv = createPrivateKey({ key: Buffer.concat([PKCS8_PREFIX, seed]), format: 'der', type: 'pkcs8' });
  return [e.name, { priv, kid: kidOf(Buffer.from(e.public_key, 'base64url')) }];
}));

// Deterministic nonce per case id, so regenerating is byte-stable.
const nonceOf = (caseId) => b64u(sha256(`mcp-jack interop sign-case nonce: ${caseId}`).subarray(0, 16));

// Bodies pinned as exact bytes; NUL and multibyte UTF-8 must survive round-trips.
const ASCII_BODY = '{"jsonrpc":"2.0","id":1,"method":"ping"}';
const CASES = [
  { id: 'empty-body', identity: 'alice', ts: 1767225600, target: '/mcp', body: Buffer.alloc(0) },
  { id: 'ascii-body', identity: 'alice', ts: 1767225600, target: '/mcp', body: Buffer.from(ASCII_BODY, 'utf8') },
  { id: 'utf8-body', identity: 'bob', ts: 1767225600, target: '/mcp', body: Buffer.from('{"q":"naïve café – 日本語 🚀"}', 'utf8') },
  { id: 'nul-newline-body', identity: 'carol', ts: 1767225600, target: '/mcp', body: Buffer.from('line1\nline2\0tail', 'utf8') },
  { id: 'query-target', identity: 'alice', ts: 1767225600, target: '/mcp/a%20path?q=na%C3%AFve&x=1&y=%2F', body: Buffer.from(ASCII_BODY, 'utf8') },
  { id: 'long-target', identity: 'alice', ts: 1767225600, target: '/mcp/' + 'segment%20one/'.repeat(8) + 'leaf?p=' + encodeURIComponent('naïve café 日本語') + '&q=' + 'x'.repeat(64), body: Buffer.alloc(0) },
  { id: 'ts-min', identity: 'alice', ts: 0, target: '/mcp', body: Buffer.from(ASCII_BODY, 'utf8') },
  { id: 'ts-max', identity: 'alice', ts: 999999999999, target: '/mcp', body: Buffer.from(ASCII_BODY, 'utf8') },
];

const doc = {
  note: 'Generated by interop/tools/gen-sign-cases.mjs, do not edit; identities are TEST-ONLY names from spec/fixtures/keys.json; oracle values pin the exact bytes of spec/01-authentication.md section 3.1.',
  cases: CASES.map(({ id, identity, ts, target, body }) => {
    const { priv, kid } = K[identity];
    const nonce = nonceOf(id);
    const signing = requestSigningString({ method: 'POST', target, aud: AUD, kid, ts, nonce, body });
    const sig = b64u(sign(null, Buffer.from(signing, 'utf8'), priv));
    return {
      id, identity, method: 'POST', target, aud: AUD, ts, nonce,
      body_b64u: b64u(body),
      expected: { kid, signing_string: signing, jack_auth: `v1 kid=${kid},ts=${ts},nonce=${nonce},sig=${sig}` },
    };
  }),
};

const text = JSON.stringify(doc, null, 2) + '\n';

if (process.argv.includes('--check')) {
  if (!existsSync(join(ROOT, OUT_REL)) || readFileSync(join(ROOT, OUT_REL), 'utf8') !== text) {
    console.error(`stale: ${OUT_REL}`);
    process.exit(1);
  }
  console.log(`ok: ${CASES.length} sign cases, oracle up to date`);
} else {
  writeFileSync(join(ROOT, OUT_REL), text);
  console.log(`wrote ${OUT_REL}: ${CASES.length} sign cases`);
}
